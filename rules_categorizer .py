def _compile(rules):
    """Разбиваем правила по направлению и заранее компилируем регулярки."""
    result = {IN: [], OUT: []}
    for direction, category, patterns in rules:
        result[direction].append((category, [re.compile(p) for p in patterns]))
    return result


_RULES = _compile(RULES)
_COUNTERPARTY_RULES = _compile(COUNTERPARTY_RULES)


def _normalize(text):
    if not isinstance(text, str):
        return ''
    return text.strip().lower().replace('ё', 'е')


def _match(text, rules):
    for category, patterns in rules:
        for pattern in patterns:
            if pattern.search(text):
                return category
    return None


def categorize_by_rules(purpose, direction, counterparty=None):
    """Категория из categories.py или None, если ни одно правило не подошло."""
    if direction not in _RULES:
        return None

    text = _normalize(purpose)
    if text:
        return _match(text, _RULES[direction])

    # назначение пустое - пробуем по контрагенту
    name = _normalize(counterparty)
    if name:
        return _match(name, _COUNTERPARTY_RULES[direction])
    return None


